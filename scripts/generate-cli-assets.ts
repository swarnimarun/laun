import { createHash } from "node:crypto";
import { resolve } from "node:path";
import { CLI_ASSET_PATHS } from "./cli-asset-list.js";
import { TELEGRAM_PLACEHOLDER_TOKEN } from "../apps/telegram-bridge/src/config.js";
export async function generateCliAssets(
  root = resolve(import.meta.dir, ".."),
): Promise<string> {
  const files: Record<string, { content: string; sha256: string }> = {};
  for (const path of [...CLI_ASSET_PATHS].sort()) {
    const content = await Bun.file(resolve(root, path)).text();
    if (path === "deploy/.env.example")
      for (const line of content.split(/\r?\n/)) {
        const entry = line.match(/^([A-Z0-9_]+)=(.*)$/);
        if (
          entry &&
          (/(?:^|_)(?:TOKEN|SECRET|PASSWORD|API_KEY|PRIVATE_KEY|INBOX_KEY)$/.test(
            entry[1]!,
          ) ||
            entry[1] === "LAUN_KEY")
        ) {
          const value = entry[2]!.trim().replace(/^['"]|['"]$/g, "");
          if (
            value &&
            !/^change-me|^<[^>]+>$/.test(value) &&
            !(
              entry[1] === "TELEGRAM_BOT_TOKEN" &&
              value === TELEGRAM_PLACEHOLDER_TOKEN
            )
          )
            throw new Error(
              `refusing to embed a configured credential field in public deployment templates: ${entry[1]}`,
            );
        }
      }
    files[path] = {
      content,
      sha256: createHash("sha256").update(content).digest("hex"),
    };
  }
  const manifest = createHash("sha256")
    .update(
      Object.entries(files)
        .map(([path, file]) => `${path}\0${file.sha256}\n`)
        .join(""),
    )
    .digest("hex");
  const output = resolve(root, "apps/laun/src/bundled-assets.generated.ts");
  await Bun.write(
    output,
    `// Generated by scripts/generate-cli-assets.ts. Public templates only; regenerate after deployment changes.\nexport const CLI_ASSET_MANIFEST=${JSON.stringify(manifest)};\nexport const CLI_ASSETS=${JSON.stringify(files, null, 2)} as const;\n`,
  );
  return output;
}
if (import.meta.main) {
  await generateCliAssets();
  console.log("Generated verified deployment templates for the portable CLI.");
}
